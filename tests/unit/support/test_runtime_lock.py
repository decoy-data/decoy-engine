BAD_LABELS = ["v1\n", "", "x" * 65, "a/b"]


@pytest.mark.parametrize("label", BAD_LABELS)
def test_a_bad_key_version_raises_the_typed_error_without_context(label: str) -> None:
    assert is_key_version_label(label) is False
    with pytest.raises(MaskSecretError) as caught:
        build_runtime_lock(key_version=label)
    assert caught.value.code == "key_version_invalid"
    assert caught.value.__cause__ is None
    assert caught.value.__context__ is None
    assert label.strip() not in str(caught.value) or not label.strip()


@pytest.mark.parametrize("label", [True, 1, ["v1"], b"v1", object()])
def test_a_non_string_key_version_is_refused_the_same_way(label: Any) -> None:
    assert is_key_version_label(label) is False
    with pytest.raises(MaskSecretError) as caught:
        build_runtime_lock(key_version=label)
    assert caught.value.code == "key_version_invalid"


@pytest.mark.parametrize("label", ["v1", "A", "a" * 64, "k:2+rc!1", "v1.2_3-4"])
def test_a_good_key_version_is_accepted(label: str) -> None:
    assert is_key_version_label(label) is True
    assert build_runtime_lock(key_version=label).key_version == label


def test_the_resume_record_and_the_lock_share_the_one_public_check(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    assert _records.is_key_version_label is is_key_version_label
    lock_doc = _sample()
    lock_doc["key_version"] = "a/b"
    run_doc = _docs.run_doc()
    run_doc["fingerprint"]["key_version"] = "a/b"
    run_bytes = _docs.canonical(run_doc)

    with pytest.raises(ValueError, match=PREFIX):
        read_runtime_lock(json.dumps(lock_doc))
    with pytest.raises(MaskSecretError):
        build_runtime_lock(key_version="a/b")
    with pytest.raises(ValueError, match="resume_record_refused:"):
        _records.decode_run_record(run_bytes)

    # Loosen the one private pattern: all three consumers follow it, so none keeps a copy.
    monkeypatch.setattr(keyprovider, "KEY_VERSION_PATTERN", r"[A-Za-z0-9/]{1,8}")
    assert read_runtime_lock(json.dumps(lock_doc)).key_version == "a/b"
    assert build_runtime_lock(key_version="a/b").key_version == "a/b"
    assert _records.decode_run_record(run_bytes).fingerprint.key_version == "a/b"


