def _patch_faker_metadata(monkeypatch: pytest.MonkeyPatch) -> None:
    real = importlib.metadata.version

    def fake(name: str) -> str:
        return "99.0.0" if name.lower() == "faker" else real(name)

    monkeypatch.setattr(importlib.metadata, "version", fake)


def _patch_provider_added(monkeypatch: pytest.MonkeyPatch) -> None:
    registry = providers_v2.get_default_registry()
    adapter = registry.get_adapter("synthetic_ssn")
    caps = registry.get_capabilities("synthetic_ssn").model_copy(update={"provider": "zz_extra"})
    extended = registry.override("zz_extra", adapter, caps)
    monkeypatch.setattr(providers_v2, "get_default_registry", lambda: extended)


def _patch_seed_protocol(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(determinism, "SEED_PROTOCOL_VERSION", determinism.SEED_PROTOCOL_VERSION + 1)


def _patch_phase(monkeypatch: pytest.MonkeyPatch) -> None:
    other = "ga" if release.RELEASE_PHASE == "pre-ga" else "pre-ga"
    monkeypatch.setattr(release, "RELEASE_PHASE", other)


def _patch_data_byte(monkeypatch: pytest.MonkeyPatch) -> None:
    files = list(_runtime_lock._data_files())
    name, blob = files[0]
    files[0] = (name, blob[:-1] + bytes([blob[-1] ^ 1]))
    monkeypatch.setattr(_runtime_lock, "_data_files", lambda: files)


@pytest.mark.parametrize(
    ("patch", "field"),
    [
        (_patch_faker_metadata, "faker"),
        (_patch_provider_added, "providers_digest"),
        (_patch_seed_protocol, "seed_protocol"),
        (_patch_phase, "compat_phase"),
        (_patch_data_byte, "data_digest"),
    ],
)
def test_each_source_changes_exactly_its_named_field(
    monkeypatch: pytest.MonkeyPatch, patch: Any, field: str
) -> None:
    before = build_runtime_lock()
    patch(monkeypatch)
    after = build_runtime_lock()
    assert _names(compare_runtime_locks([before, after])) == [field]


def test_compare_reports_each_lock_value_in_input_order_and_nothing_when_equal() -> None:
    a = build_runtime_lock(key_version="v1")
    b = dataclasses.replace(a, key_version="v2")
    c = dataclasses.replace(a, key_version="v3")
    [diff] = compare_runtime_locks([a, b, c])
    assert diff.field == "key_version"
    assert diff.values == ("v1", "v2", "v3")
    assert compare_runtime_locks([a, a]) == ()
    assert compare_runtime_locks([a]) == ()


def test_compare_names_dependencies_as_one_field() -> None:
    a = build_runtime_lock()
    deps = (*a.dependencies, ("zzz-extra", "1.0"))
    changed = dataclasses.replace(a, dependencies=deps)
    assert _names(compare_runtime_locks([a, changed])) == ["dependencies"]


def test_compare_refuses_a_non_lock() -> None:
    with pytest.raises(TypeError):
        compare_runtime_locks([build_runtime_lock(), {"engine": "x"}])  # type: ignore[list-item]


def test_dependencies_come_from_distribution_metadata_without_a_second_list() -> None:
    names = {name for name, _ in build_runtime_lock().dependencies}
    # Each of these has its own field, so it never repeats in dependencies.
    assert names.isdisjoint({"numpy", "pandas", "pyarrow", "faker"})
    assert {"polars", "duckdb"} <= names


# AT-78-E4 --------------------------------------------------------------------------------------


def test_lock_holds_no_key_check_path_or_host(tmp_path: Path) -> None:
    secret = bytes(range(33, 65))
    provider = SecretKeyProvider(secret, "v1")
    fingerprint = build_fingerprint(
        {"pipeline": {"name": "p"}}, provider, chunk_size=10, components=[("a", "1")]
    )
    text = build_runtime_lock(key_version=provider.key_version).to_json()
    assert secret.hex() not in text
    assert provider.mask_key().hex() not in text
    assert fingerprint.key_check not in text
    assert str(tmp_path) not in text
    assert socket.gethostname() not in text
    assert json.loads(text)["key_version"] == "v1"


