"""AT-78-E1 to AT-78-E6: the `lock/v1` runtime lock envelope (release-chain plan, slice 78-E1).

The lock records what masked or generated bytes depend on. These cells pin that it is the same
bytes in every process, that each source feeds exactly one field, that it holds no secret, no
path and no host name, that the key version label has one rule, and that the writer and the
reader are strict about types.
"""

