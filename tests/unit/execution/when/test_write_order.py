def _two_joint_writers(tmp_path: Path, first: str, second: str) -> pa.Table:
    """`first` is declared before `second`; each joint mask writes its own column and `shared`
    from a distinct one-row reference."""
    ref1 = ws.reference(tmp_path / "r1.parquet", **{first: ["ONE"], "shared": ["S-ONE"]})
    ref2 = ws.reference(tmp_path / "r2.parquet", **{second: ["TWO"], "shared": ["S-TWO"]})
    table = pa.table(
        {
            "k": pa.array(["a", "b"]),
            first: pa.array(["p", "q"]),
            second: pa.array(["r", "s"]),
            "shared": pa.array(["m", "n"]),
        }
    )
    seed_plan = ws.plan(
        [
            (first, ws.joint(ref1, [first, "shared"])),
            (second, ws.joint(ref2, [second, "shared"])),
        ]
    )
    return ws.run(seed_plan, table)


def test_equal_priority_writer_spelling_swap(tmp_path: Path) -> None:
    """10. Two ungated writers of one column: the larger ready key writes last, whatever the
    declaration order."""
    out = _two_joint_writers(tmp_path, "z_first", "a_second")
    assert out.column("shared").to_pylist() == ["S-ONE", "S-ONE"]
    out = _two_joint_writers(tmp_path, "a_first", "z_second")
    assert out.column("shared").to_pylist() == ["S-TWO", "S-TWO"]


