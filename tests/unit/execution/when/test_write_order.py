"""Write and ordering model, acceptance tests 1 to 5, 7, 10, 12 and 16, plus the composite
commit-boundary guard.

Plan: `docs/plans/2026-11-22-when-reads-source.md`, "Write and ordering model". Each column
commits in dispatch rank and the last writer wins. Every plan that runs today keeps today's
output; the new ordering applies only where today's sort raises a cycle.
"""

from __future__ import annotations

from pathlib import Path

import pyarrow as pa
import pytest

from decoy_engine.execution._errors import ExecutionError
from tests.unit.execution.when import _write_support as ws

N = 4
FIRST = [f"F{i}" for i in range(N)]


def test_coherent_member_reads_generated_email() -> None:
    """1. A `coherent_with` member outside the bundle writes nothing, so `summary` waits for
    the composite and reads its generated email."""
    source_email = [f"u{i}@x.test" for i in range(N)]
    table = pa.table(
        {
            "first_name": pa.array(FIRST),
            "last_name": pa.array([f"L{i}" for i in range(N)]),
            "email": pa.array(source_email),
            "summary": pa.array(["x"] * N),
        }
    )
    seed_plan = ws.plan(
        [
            ("first_name", ws.bundle(coherent_with=("summary",))),
            ("summary", ws.derived('concat(email, "!")')),
        ]
    )
    out = ws.run(seed_plan, table, bound=(("first_name", "summary"),))
    emails = out.column("email").to_pylist()
    summary = out.column("summary").to_pylist()
    assert summary == [e + "!" for e in emails]
    assert all(s != e + "!" for s, e in zip(summary, source_email, strict=True))


def _surname_fixture(child: str) -> tuple[pa.Table, list[str]]:
    """`last_name` is derived from `other` and also generated by the bundle; `child` is an FK
    child of `last_name` holding the original surnames in permuted order."""
    surnames = [f"Sur{i}" for i in range(N)]
    permuted = [surnames[i] for i in (2, 0, 3, 1)]
    table = pa.table(
        {
            "first_name": pa.array(FIRST),
            "last_name": pa.array(surnames),
            "email": pa.array([f"u{i}@x.test" for i in range(N)]),
            "other": pa.array([f"O{i}" for i in range(N)]),
            child: pa.array(permuted),
        }
    )
    return table, permuted


def _surname_run(child: str) -> tuple[pa.Table, pa.Table]:
    table, _ = _surname_fixture(child)
    seed_plan = ws.plan(
        [
            ("first_name", ws.bundle()),
            ("last_name", ws.derived('concat(other, "?")')),
            (child, ws.seed("passthrough")),
        ]
    )
    return table, ws.run(seed_plan, table, ws.fk_graph("last_name", child))


def test_fk_reads_final_bundle_surname() -> None:
    """2. The parent map pairs each ORIGINAL parent key with the FINAL key of its row, the
    bundle's surname, never the intermediate derived value."""
    table, out = _surname_run("a_ref")
    oracle = ws.bundle_oracle(FIRST)["last_name"]
    by_original = dict(zip(table.column("last_name").to_pylist(), oracle, strict=True))
    children = out.column("a_ref").to_pylist()
    assert children == [by_original[s] for s in table.column("a_ref").to_pylist()]
    derived_values = {o + "?" for o in table.column("other").to_pylist()}
    assert not derived_values & set(children)


def test_renaming_child_preserves_output() -> None:
    """7. Renaming the FK child changes its key and so its place in the ready queue; it must
    not change any output."""
    _, a_out = _surname_run("a_ref")
    _, z_out = _surname_run("z_ref")
    z_back = z_out.rename_columns(["a_ref" if c == "z_ref" else c for c in z_out.column_names])
    assert z_back.to_pydict() == a_out.to_pydict()


def test_fk_child_bypasses_derived_creator() -> None:
    """3. `email` resolves through the `first_name` parent map. Its derived expression is never
    run, so it adds no read of `other` and no creator edge against the bundle."""
    table = pa.table(
        {
            "first_name": pa.array(FIRST),
            "last_name": pa.array([f"L{i}" for i in range(N)]),
            "email": pa.array(FIRST),
            "other": pa.array([f"O{i}" for i in range(N)]),
        }
    )
    seed_plan = ws.plan([("first_name", ws.bundle()), ("email", ws.derived('concat(other, "#")'))])
    out = ws.run(seed_plan, table, ws.fk_graph("first_name", "email"))
    assert out.column("email").to_pylist() == out.column("first_name").to_pylist()
    assert out.column("last_name").to_pylist() == ws.bundle_oracle(FIRST)["last_name"]


def test_indirect_creator_reads_after_bundle() -> None:
    """4. `email` (creator, overwritten by the bundle) reads `summary`, which reads the bundle's
    `last_name`. Today's constraints form a cycle; the commit ranks put the creator's email
    below the bundle while evaluation waits for `summary`."""
    table = pa.table(
        {
            "first_name": pa.array(FIRST),
            "last_name": pa.array([f"L{i}" for i in range(N)]),
            "email": pa.array([f"u{i}@x.test" for i in range(N)]),
            "summary": pa.array(["x"] * N),
        }
    )
    seed_plan = ws.plan(
        [
            ("first_name", ws.bundle()),
            ("email", ws.derived('concat(summary, "@x.test")')),
            ("summary", ws.derived('concat(last_name, "!")')),
        ]
    )
    out = ws.run(seed_plan, table)
    oracle = ws.bundle_oracle(FIRST)
    assert out.column("summary").to_pylist() == [s + "!" for s in oracle["last_name"]]
    assert out.column("email").to_pylist() == oracle["email"]


@pytest.mark.parametrize("with_bundle", [False, True], ids=["creator-only", "with-bundle"])
def test_zero_match_creator_supplies_missing_target(with_bundle: bool) -> None:
    """5. A gated creator that matches no row still admits its missing target: the column
    exists and is null, and a bundle can fill it."""
    table = pa.table(
        {
            "first_name": pa.array(FIRST),
            "last_name": pa.array([f"L{i}" for i in range(N)]),
            "flag": pa.array(["n"] * N),
        }
    )
    creator = ("email", ws.derived('concat(last_name, "@x.test")', when="flag == 'y'"))
    per_column = [("first_name", ws.bundle()), creator] if with_bundle else [creator]
    out = ws.run(ws.plan(per_column), table)
    emails = out.column("email").to_pylist()
    if with_bundle:
        assert emails == ws.bundle_oracle(FIRST)["email"]
    else:
        assert emails == [None] * N


def _two_joint_writers(tmp_path: Path, first: str, second: str) -> pa.Table:
    """`first` is declared before `second`; each joint mask writes its own column and `shared`
    from a distinct one-row reference."""
    ref1 = ws.reference(tmp_path / "r1.parquet", **{first: ["ONE"], "shared": ["S-ONE"]})
    ref2 = ws.reference(tmp_path / "r2.parquet", **{second: ["TWO"], "shared": ["S-TWO"]})
    table = pa.table(
        {
            "k": pa.array(["a", "b"]),
            first: pa.array(["p", "q"]),
            second: pa.array(["r", "s"]),
            "shared": pa.array(["m", "n"]),
        }
    )
    seed_plan = ws.plan(
        [
            (first, ws.joint(ref1, [first, "shared"])),
            (second, ws.joint(ref2, [second, "shared"])),
        ]
    )
    return ws.run(seed_plan, table)


def test_equal_priority_writer_spelling_swap(tmp_path: Path) -> None:
    """10. Two ungated writers of one column: the larger ready key writes last, whatever the
    declaration order."""
    out = _two_joint_writers(tmp_path, "z_first", "a_second")
    assert out.column("shared").to_pylist() == ["S-ONE", "S-ONE"]
    out = _two_joint_writers(tmp_path, "a_first", "z_second")
    assert out.column("shared").to_pylist() == ["S-TWO", "S-TWO"]


def test_zip_city_state_matches_current_output(tmp_path: Path) -> None:
    """12. Two ungated joint masks both write `state`; the output observed at d74afd71c stays."""
    zip_ref = ws.reference(tmp_path / "z.parquet", zip=["ZIP"], state=["zip-state"])
    city_ref = ws.reference(tmp_path / "c.parquet", city=["CITY"], state=["city-state"])
    table = pa.table(
        {
            "k": pa.array(["a", "b"]),
            "zip": pa.array(["x", "y"]),
            "city": pa.array(["m", "n"]),
            "state": pa.array(["s", "t"]),
        }
    )
    seed_plan = ws.plan(
        [
            ("zip", ws.joint(zip_ref, ["zip", "state"])),
            ("city", ws.joint(city_ref, ["city", "state"])),
        ]
    )
    expected = pa.table(
        {
            "k": pa.array(["a", "b"]),
            "zip": pa.array(["ZIP", "ZIP"]),
            "city": pa.array(["CITY", "CITY"]),
            "state": pa.array(["zip-state", "zip-state"]),
        }
    )
    assert ws.run(seed_plan, table).equals(expected, check_metadata=False)


def test_fk_preserves_state_written_by_joint_mask(tmp_path: Path) -> None:
    """16. The FK child reads the `state` visible at its dispatch rank: the joint mask's PA,
    preserved as an orphan, not the source value."""
    ref = ws.reference(tmp_path / "c.parquet", city=["CITY"], state=["PA"])
    table = pa.table(
        {
            "k": pa.array(["a"]),
            "p": pa.array(["P1"]),
            "city": pa.array(["m"]),
            "state": pa.array(["original"]),
        }
    )
    seed_plan = ws.plan(
        [("city", ws.joint(ref, ["city", "state"])), ("state", ws.seed("passthrough"))]
    )
    out = ws.run(seed_plan, table, ws.fk_graph("p", "state"))
    assert out.column("state").to_pylist() == ["PA"]


def test_bundle_with_an_undeclared_key_is_refused(monkeypatch: pytest.MonkeyPatch) -> None:
    """Commit boundary: a generated key outside the bundle's declared outputs is refused before
    any assignment, even when the frame has that column."""
    from decoy_engine.generation.composite import _name_email

    real = _name_email.CompositeNameEmail.generate_bundle

    def with_extra(self, *args, **kwargs):  # type: ignore[no-untyped-def]
        out = dict(real(self, *args, **kwargs))
        out["other"] = ["leak"] * N
        return out

    monkeypatch.setattr(_name_email.CompositeNameEmail, "generate_bundle", with_extra)
    table = pa.table(
        {
            "first_name": pa.array(FIRST),
            "last_name": pa.array([f"L{i}" for i in range(N)]),
            "email": pa.array([f"u{i}@x.test" for i in range(N)]),
            "other": pa.array(["keep"] * N),
        }
    )
    with pytest.raises(ExecutionError) as exc:
        ws.run(ws.plan([("first_name", ws.bundle())]), table)
    assert exc.value.code == "composite_output_column_missing"
