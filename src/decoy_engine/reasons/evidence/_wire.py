WIRE_IDENTITY: Mapping[str, ReasonCode] = MappingProxyType(
    {token: identity for identity, token in WIRE_TOKEN.items()}
)


class Prefix(Enum):
    """The wrappers that put a strict-reader code under a document name."""

    STATEMENT = "STATEMENT"
    TRUST_POLICY = "TRUST_POLICY"
    CATALOG = "CATALOG"
    EXPECTATIONS = "EXPECTATIONS"
    ENVELOPE = "ENVELOPE"


#: The strict-reader codes a document wrapper can receive.
INNER_CODES: tuple[ReasonCode, ...] = (
    _s.BOM,
    _s.DUPLICATE_MEMBER,
    _s.FLOAT_NOT_ALLOWED,
    _s.INTEGER_OUT_OF_DOMAIN,
    _s.INVALID_UNICODE,
    _s.NON_FINITE_NUMBER,
    _s.NOT_JSON,
    _s.NOT_UTF8,
    _s.TOO_DEEP,
    _s.TOO_LARGE,
    _s.TOO_MANY_NODES,
)
_ENVELOPE_INNER = frozenset(INNER_CODES) - {_s.BOM, _s.NOT_UTF8, _s.NOT_JSON}


def _closed_product() -> dict[tuple[Prefix, ReasonCode], ReasonCode]:
    table: dict[tuple[Prefix, ReasonCode], ReasonCode] = {}
    for prefix in Prefix:
        for inner in INNER_CODES:
            if prefix is Prefix.ENVELOPE and inner not in _ENVELOPE_INNER:
                continue
            token = f"{prefix.value}_{WIRE_TOKEN[inner]}"
            table[(prefix, inner)] = WIRE_IDENTITY[token]  # a missing row fails the import
    return table


_COMPOSITE = _closed_product()


def wire_for(prefix: Prefix, inner: ReasonCode) -> ReasonCode:
    """The identity of ``<PREFIX>_<INNER>``. Raises ``KeyError`` for a pair outside the product."""
    return _COMPOSITE[(prefix, inner)]
